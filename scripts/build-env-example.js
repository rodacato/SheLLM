#!/usr/bin/env node
'use strict';

// Renders .env.example from src/config/schema.js. CI regenerates and diffs, so the committed file
// is the schema's output and never a thing a human keeps in step. See docs/adr/0008.

const fs = require('node:fs');
const path = require('node:path');
const schema = require('../src/config/schema');

const ROOT = path.join(__dirname, '..');
const TARGET = path.join(ROOT, '.env.example');
const WIDTH = 100;

const HEADER = `# SheLLM configuration — the live copy is ~/.config/shellm/env (mode 600), written by \`shellm init\`.
# Nothing reads this file at runtime, with one exception: the dev container installs a copy of it
# as that config when none exists, and every secret here is commented out, so \`shellm init\` is
# still what makes /admin/* answer.
#
# GENERATED by \`npm run config:build\` from src/config/schema.js. Edit the schema, not this file.`;

function wrap(text) {
  const lines = [];
  for (const paragraph of text.trim().split('\n')) {
    let current = '';
    for (const word of paragraph.trim().split(/\s+/)) {
      if (current && `${current} ${word}`.length > WIDTH - 2) {
        lines.push(current);
        current = word;
      } else {
        current = current ? `${current} ${word}` : word;
      }
    }
    lines.push(current);
  }
  return lines.map((line) => (line ? `# ${line}` : '#'));
}

// A secret never carries a value, so a copied file cannot ship one.
function assignment(name, entry) {
  if (entry.secret) return `# ${name}=`;
  const value = entry.example ?? (entry.default === null ? '' : entry.default);
  return entry.prominent ? `${name}=${value}` : `# ${name}=${value}`;
}

function render() {
  const sections = new Map();
  for (const [name, entry] of Object.entries(schema)) {
    if (!sections.has(entry.section)) sections.set(entry.section, []);
    sections.get(entry.section).push([name, entry]);
  }

  const out = [HEADER];
  for (const [section, entries] of sections) {
    out.push('', `# --- ${section} ---`);
    for (const [name, entry] of entries) {
      out.push('', ...wrap(entry.describe), assignment(name, entry));
    }
  }
  return `${out.join('\n')}\n`;
}

// Required by the suite so a stale .env.example fails locally, not only in CI.
if (require.main === module) {
  const rendered = render();
  const previous = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  fs.writeFileSync(TARGET, rendered);
  const verb = previous === rendered ? 'unchanged' : 'written';
  console.log(`.env.example ${verb} — ${Object.keys(schema).length} settings`);
}

module.exports = { render, TARGET };
